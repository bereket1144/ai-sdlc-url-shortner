package io.github.bereket1144.agentcontroller.modelcall;

import java.util.UUID;
import java.util.stream.Collectors;

import io.github.bereket1144.agentcontroller.model.ModelClient.FinishReason;
import io.github.bereket1144.agentcontroller.model.ModelClient.ModelResult;
import io.github.bereket1144.agentcontroller.model.ModelProfile;
import io.github.bereket1144.agentcontroller.modelcall.ModelCallRecords.Attempt;
import io.github.bereket1144.agentcontroller.modelcall.ModelCallRecords.AttemptKind;
import io.github.bereket1144.agentcontroller.modelcall.ModelCallRecords.Outcome;
import io.github.bereket1144.agentcontroller.modelcall.ModelCallRecords.StoredAttempt;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.Immutable;

/**
 * One row of {@code model_call}. It has no setters, and {@link Immutable} makes Hibernate ignore any change to a
 * loaded row, so a stored record is never changed. It is package-private: the rest of the platform sees only
 * {@link StoredAttempt}. The column {@code recorded_at} is filled by the database and is not mapped.
 */
@Entity
@Table(name = "model_call")
@Immutable
class ModelCallEntity {

    // Generated by the database (an identity column), which gives the order the attempts were recorded in.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private UUID runId;

    @Column(nullable = false)
    private String role;

    @Column(nullable = false)
    private String roleVersion;

    @Column(nullable = false)
    private String profile;

    @Column(nullable = false)
    private String model;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private AttemptKind attemptKind;

    @Column(nullable = false, length = 64)
    private String inputFingerprint;

    @Column(nullable = false, columnDefinition = "text")
    private String systemText;

    @Column(nullable = false, columnDefinition = "text")
    private String userText;

    @Column(columnDefinition = "text")
    private String answerText;

    @Enumerated(EnumType.STRING)
    private FinishReason finishReason;

    @Column(nullable = false)
    private long estimatedPromptTokens;

    private Long estimatedAnswerTokens;

    private Long reportedPromptTokens;

    private Long reportedAnswerTokens;

    // One "index:KIND:version" entry per reduction step, joined by ";". Empty when the prompt was not reduced.
    @Column(nullable = false, columnDefinition = "text")
    private String reductionSteps;

    @Column(nullable = false)
    private long durationMs;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Outcome outcome;

    // JPA uses this when it loads an existing row.
    protected ModelCallEntity() {
    }

    ModelCallEntity(Attempt attempt, String roleVersion) {
        ModelProfile modelProfile = attempt.profile();
        this.runId = attempt.runId();
        this.role = attempt.role();
        this.roleVersion = roleVersion;
        this.profile = modelProfile.name();
        this.model = modelProfile.model();
        this.attemptKind = attempt.kind();
        this.inputFingerprint = InputFingerprint.of(modelProfile.name(), attempt.systemText(), attempt.userText());
        this.systemText = attempt.systemText();
        this.userText = attempt.userText();
        ModelResult result = attempt.result();
        if (result != null) {
            this.answerText = result.text();
            this.finishReason = result.finishReason();
            this.reportedPromptTokens = result.promptTokens();
            this.reportedAnswerTokens = result.answerTokens();
        }
        this.estimatedPromptTokens = attempt.estimatedPromptTokens();
        this.estimatedAnswerTokens = attempt.estimatedAnswerTokens();
        this.reductionSteps = attempt.reductions().stream()
                .map(step -> step.inputIndex() + ":" + step.kind() + ":" + step.version())
                .collect(Collectors.joining(";"));
        this.durationMs = attempt.duration().toMillis();
        this.outcome = attempt.outcome();
    }

    StoredAttempt toStoredAttempt() {
        return new StoredAttempt(id, runId, role, roleVersion, profile, model, attemptKind, inputFingerprint,
                systemText, userText, answerText, finishReason, estimatedPromptTokens, estimatedAnswerTokens,
                reportedPromptTokens, reportedAnswerTokens, reductionSteps, durationMs, outcome);
    }
}
