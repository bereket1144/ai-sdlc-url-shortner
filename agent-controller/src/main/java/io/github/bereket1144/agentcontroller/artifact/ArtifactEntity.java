package io.github.bereket1144.agentcontroller.artifact;

import java.util.Arrays;
import java.util.List;
import java.util.UUID;
import java.util.stream.Collectors;

import io.github.bereket1144.agentcontroller.artifact.ArtifactStore.StoredArtifact;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.Immutable;
import tools.jackson.databind.json.JsonMapper;

/**
 * One row of {@code artifact}. It has no setters, and {@link Immutable} makes Hibernate ignore any change to a loaded
 * row, so a stored version is never changed. It is package-private: the rest of the platform sees only
 * {@link StoredArtifact} and {@link ArtifactRef}. The column {@code created_at} is filled by the database and is not
 * mapped.
 */
@Entity
@Table(name = "artifact")
@Immutable
class ArtifactEntity {

    // Generated by the database (an identity column), which gives the order the artifacts were stored in.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private UUID runId;

    @Column(nullable = false)
    private String kind;

    @Column(nullable = false)
    private int version;

    @Column(nullable = false, columnDefinition = "text")
    private String content;

    @Column(nullable = false, columnDefinition = "text")
    private String summary;

    @Column(nullable = false, length = 64)
    private String fingerprint;

    @Column(nullable = false)
    private String role;

    @Column(nullable = false)
    private String roleVersion;

    @Column(nullable = false)
    private String profile;

    @Column(nullable = false)
    private String model;

    // One "kind:version:fingerprint" entry per consumed artifact version, joined by ";". Empty for none.
    @Column(nullable = false, columnDefinition = "text")
    private String consumed;

    // JPA uses this when it loads an existing row.
    protected ArtifactEntity() {
    }

    ArtifactEntity(UUID runId, String kind, int version, String content, String summary, String fingerprint,
                   String role, String roleVersion, String profile, String model, List<ArtifactRef> consumed) {
        this.runId = runId;
        this.kind = kind;
        this.version = version;
        this.content = content;
        this.summary = summary;
        this.fingerprint = fingerprint;
        this.role = role;
        this.roleVersion = roleVersion;
        this.profile = profile;
        this.model = model;
        this.consumed = consumed.stream()
                .map(ref -> ref.kind() + ":" + ref.version() + ":" + ref.fingerprint())
                .collect(Collectors.joining(";"));
    }

    int version() {
        return version;
    }

    ArtifactRef toRef() {
        return new ArtifactRef(kind, version, fingerprint);
    }

    StoredArtifact toStoredArtifact(JsonMapper mapper) {
        List<ArtifactRef> consumedRefs = consumed.isEmpty() ? List.of() : Arrays.stream(consumed.split(";"))
                .map(entry -> entry.split(":"))
                .map(parts -> new ArtifactRef(parts[0], Integer.parseInt(parts[1]), parts[2]))
                .toList();
        return new StoredArtifact(runId, kind, version, mapper.readTree(content), summary, fingerprint, role,
                roleVersion, profile, model, consumedRefs);
    }
}
